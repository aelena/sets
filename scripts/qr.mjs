/**
 * Regenerates the QR code that points people at the app (Settings → Share Sets), from the live URL.
 * Writes the module the app renders from (src/lib/qr.js) and a PNG for the README. Run once per URL
 * change: `node scripts/qr.mjs`. The app does not need the qrcode package at runtime.
 */
import { writeFileSync } from 'node:fs'
import QRCode from 'qrcode'

export const URL = 'https://aelena.com/sets/'

const qr = QRCode.create(URL, { errorCorrectionLevel: 'M' })
const size = qr.modules.size
const rows = []
for (let y = 0; y < size; y++) {
  let row = ''
  for (let x = 0; x < size; x++) row += qr.modules.get(y, x) ? '#' : '.'
  rows.push(row)
}

writeFileSync('src/lib/qr.js', `/**
 * The QR code for ${URL}, as rows of modules ('#' dark). Generated by scripts/qr.mjs; do not edit.
 */
export const QR_URL = '${URL}'
export const QR_LABEL = 'aelena.com/sets'
export const QR_ROWS = [
${rows.map(r => `  '${r}',`).join('\n')}
]

/** One SVG path drawing every dark module as a unit square; viewBox 0 0 size size. */
export const qrPath = () => QR_ROWS.flatMap((row, y) => [...row].map((c, x) => (c === '#' ? \`M\${x} \${y}h1v1h-1z\` : ''))).join('')
`)

writeFileSync('docs/sets-qr.png', await QRCode.toBuffer(URL, { errorCorrectionLevel: 'M', width: 640, margin: 2 }))
console.log(`qr: ${size}×${size} modules → src/lib/qr.js, docs/sets-qr.png`)
